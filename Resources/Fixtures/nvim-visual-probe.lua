-- Synthetic in-memory buffers; no user configuration or history.
local results = {}
local function run(name, lines, keys)
  vim.cmd.enew({ bang = true })
  vim.api.nvim_buf_set_lines(0, 0, -1, false, lines)
  vim.api.nvim_win_set_cursor(0, {1, 0})
  vim.cmd.normal({args={vim.api.nvim_replace_termcodes(keys,true,false,true)},bang=true})
  local p = vim.api.nvim_win_get_cursor(0)
  local prefix = vim.api.nvim_get_current_line():sub(1,p[2])
  results[name] = {lines=vim.api.nvim_buf_get_lines(0,0,-1,false),row=p[1]-1,column=vim.fn.strchars(prefix),mode=vim.fn.mode(),register=vim.fn.getreg('"')}
end
