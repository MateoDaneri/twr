local function keys(text) vim.api.nvim_feedkeys(vim.api.nvim_replace_termcodes(text, true, false, true), "xt", false) end
local a = vim.api.nvim_create_buf(false, true)
local b = vim.api.nvim_create_buf(false, true)
vim.api.nvim_buf_set_lines(a, 0, -1, false, {"abc"})
vim.api.nvim_buf_set_lines(b, 0, -1, false, {"def"})
vim.api.nvim_set_current_buf(a)
keys("iX<Esc>")
vim.api.nvim_set_current_buf(b)
keys(".")
print("dot_in_other_buffer=" .. vim.api.nvim_get_current_line())
vim.api.nvim_set_current_buf(a)
keys("qaA!<Esc>q")
print("macro_register="..vim.fn.getreg("a"))
vim.api.nvim_set_current_buf(b)
keys("@a")
print("macro_in_other_buffer=" .. vim.api.nvim_get_current_line())
vim.api.nvim_set_current_buf(a)
keys("@@")
print("last_macro_in_other_buffer=" .. vim.api.nvim_get_current_line())
vim.cmd("qa!")
