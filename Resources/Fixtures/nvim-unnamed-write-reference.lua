local root=assert(vim.env.TWR_RESEARCH_ROOT)
assert(root:match('^/private/tmp/twr%-unnamed%-write%-[%w]+$'))
assert(vim.uv.fs_realpath(root)==root and not vim.uv.fs_lstat(root..'/new.txt'))
local old=vim.api.nvim_get_current_buf()
vim.api.nvim_buf_set_lines(0,0,-1,false,{'SYNTHETIC'})
vim.cmd.write(root..'/new.txt')
local alt=vim.fn.bufnr('#')
print(vim.json.encode({before=old,after=vim.api.nvim_get_current_buf(),alternate=alt,name=vim.fn.bufnr(root..'/new.txt'),alternate_name=alt>0 and vim.api.nvim_buf_get_name(alt) or false}))
vim.cmd('qa!')
